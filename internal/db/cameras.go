package db

import (
	"database/sql"
	"fmt"
)

// compactCamerasIfNeeded 修复“0004 已经跑过、但表还是旧宽表”的本地库：
// 早期版本为摄像机存了 channel/ip/port/username/password/osd 等列，新代码只写
// name/rtsp_url/enabled，旧列的 NOT NULL 约束会让 INSERT 直接 500。
// 新库用最终版 0004 建表，这里探测到 rtsp_url 列就跳过，不动数据。
func compactCamerasIfNeeded(dbs *sql.DB, d Dialect) error {
	rows, err := dbs.Query(`SELECT rtsp_url FROM cameras LIMIT 0`)
	if err == nil {
		rows.Close()
		return nil
	}
	// 表本身不存在时无需迁移（理论上 0004 已建表）。
	probe, err := dbs.Query(`SELECT name FROM cameras LIMIT 0`)
	if err != nil {
		return nil
	}
	probe.Close()

	var stmts []string
	switch d.Name() {
	case MySQL:
		stmts = []string{
			`CREATE TABLE cameras_compact (
				id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
				name VARCHAR(64) NOT NULL,
				rtsp_url VARCHAR(512) NOT NULL,
				enabled TINYINT(1) NOT NULL DEFAULT 1,
				created_at VARCHAR(32) NOT NULL,
				updated_at VARCHAR(32) NOT NULL,
				UNIQUE KEY uk_cameras_compact_rtsp (rtsp_url)
			) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`,
			`INSERT INTO cameras_compact (name, rtsp_url, enabled, created_at, updated_at)
			 SELECT name, CONCAT('rtsp://', ip, ':', port, '/live'), enabled, created_at, updated_at FROM cameras`,
			`DROP TABLE cameras`,
			`RENAME TABLE cameras_compact TO cameras`,
		}
	case Postgres:
		stmts = []string{
			`CREATE TABLE cameras_compact (
				id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
				name TEXT NOT NULL,
				rtsp_url TEXT NOT NULL,
				enabled SMALLINT NOT NULL DEFAULT 1,
				created_at TEXT NOT NULL,
				updated_at TEXT NOT NULL,
				UNIQUE (rtsp_url)
			)`,
			`INSERT INTO cameras_compact (name, rtsp_url, enabled, created_at, updated_at)
			 SELECT name, 'rtsp://' || ip || ':' || port || '/live', enabled, created_at, updated_at FROM cameras`,
			`DROP TABLE cameras`,
			`ALTER TABLE cameras_compact RENAME TO cameras`,
		}
	default: // SQLite
		stmts = []string{
			`CREATE TABLE cameras_compact (
				id INTEGER PRIMARY KEY AUTOINCREMENT,
				name TEXT NOT NULL,
				rtsp_url TEXT NOT NULL,
				enabled INTEGER NOT NULL DEFAULT 1,
				created_at TEXT NOT NULL,
				updated_at TEXT NOT NULL,
				UNIQUE (rtsp_url)
			)`,
			`INSERT INTO cameras_compact (name, rtsp_url, enabled, created_at, updated_at)
			 SELECT name, 'rtsp://' || ip || ':' || port || '/live', enabled, created_at, updated_at FROM cameras`,
			`DROP TABLE cameras`,
			`ALTER TABLE cameras_compact RENAME TO cameras`,
		}
	}

	for _, stmt := range stmts {
		if _, err := dbs.Exec(stmt); err != nil {
			return fmt.Errorf("compact cameras: %w", err)
		}
	}
	return nil
}
